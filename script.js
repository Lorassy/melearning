function translatePage(language) {
  const elements = document.querySelectorAll("[data-translate]");
  const placeholderElements = document.querySelectorAll(
    "[data-placeholder-translate]",
  );

  elements.forEach((element) => {
    const key = element.getAttribute("data-translate");
    const translation = getNestedTranslation(translations[language], key);
    if (translation) {
      if (typeof translation === "string" && translation.includes("<")) {
        element.innerHTML = translation;
      } else {
        element.textContent = translation;
      }
    }
  });

  placeholderElements.forEach((element) => {
    const key = element.getAttribute("data-placeholder-translate");
    const translation = getNestedTranslation(translations[language], key);
    if (translation) {
      element.placeholder = translation;
    }
  });

  const currentLangEl = document.getElementById("currentLang");
  const currentLangFlagEl = document.getElementById("currentLangFlag");
  if (currentLangEl) currentLangEl.textContent = language.toUpperCase();
  if (currentLangFlagEl) currentLangFlagEl.className = flagMap[language] || "";

  // Inject flags into all dropdown .lang-flag spans via CSS class
  document.querySelectorAll(".lang-flag").forEach((el) => {
    const lang = el.closest("[data-lang]")?.getAttribute("data-lang");
    if (lang) el.className = flagMap[lang] || "lang-flag";
  });

  document.documentElement.lang = language;

  updateSeoForLanguage(language);

  // Translate hardcoded structural elements (nav, mega panel, footer, mobile menu)
  translateStructural(language);

  // Save to localStorage
  localStorage.setItem("language", language);
  currentLanguage = language;
}

function getNestedTranslation(obj, path) {
  return path.split(".").reduce((current, key) => {
    return current && current[key] !== undefined ? current[key] : null;
  }, obj);
}

