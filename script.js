let isMobileMenuOpen = false;

function toggleMobileMenu() {
  const mobileMenuBtn = document.getElementById("mobileMenuBtn");
  const mobileMenu = document.getElementById("mobileMenu");

  if (!mobileMenu || !mobileMenuBtn) return;

  isMobileMenuOpen = !isMobileMenuOpen;
  const hamburgerLines = mobileMenuBtn.querySelectorAll(".hamburger-line");

  if (isMobileMenuOpen) {
    mobileMenu.classList.add("is-open");
    mobileMenu.setAttribute("aria-hidden", "false");
    document.body.classList.add("km-menu-open");

    if (hamburgerLines.length === 3) {
      hamburgerLines[0].style.transform = "rotate(45deg) translate(5px, 5px)";
      hamburgerLines[1].style.opacity = "0";
      hamburgerLines[2].style.transform = "rotate(-45deg) translate(7px, -6px)";
    }
  } else {
    mobileMenu.classList.remove("is-open");
    mobileMenu.setAttribute("aria-hidden", "true");
    document.body.classList.remove("km-menu-open");

    // Reset accordion state so menu reopens with dropdowns collapsed
    ["mobileFeatLinks", "mobileUcLinks"].forEach((id) => {
      const el = document.getElementById(id);
      if (el && !el.classList.contains("hidden")) el.classList.add("hidden");
    });
    ["mobileFeatChevron", "mobileUcChevron"].forEach((id) => {
      const el = document.getElementById(id);
      if (el) el.style.transform = "";
    });

    if (hamburgerLines.length === 3) {
      hamburgerLines[0].style.transform = "";
      hamburgerLines[1].style.opacity = "1";
      hamburgerLines[2].style.transform = "";
    }

    setTimeout(() => {
      if (typeof updateNavbarOnScroll === "function") updateNavbarOnScroll();
    }, 300);
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const mobileMenuBtn = document.getElementById("mobileMenuBtn");
  const mobileMenu = document.getElementById("mobileMenu");

  if (mobileMenuBtn) {
    mobileMenuBtn.addEventListener("click", (e) => {
      e.stopPropagation();
      toggleMobileMenu();
    });
  }

  // Close button
  const mobileMenuClose = document.getElementById("mobileMenuClose");
  if (mobileMenuClose) {
    mobileMenuClose.addEventListener("click", () => {
      if (isMobileMenuOpen) {
        toggleMobileMenu();
      }
    });
  }

  if (mobileMenu) {
    const menuLinks = mobileMenu.querySelectorAll(".mobile-menu-link");
    menuLinks.forEach((link) => {
      link.addEventListener("click", () => {
        if (isMobileMenuOpen) {
          toggleMobileMenu();
        }
      });
    });
  }

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && isMobileMenuOpen) {
      toggleMobileMenu();
    }
  });

  document.addEventListener("click", (e) => {
    if (
      isMobileMenuOpen &&
      mobileMenu &&
      !mobileMenu.contains(e.target) &&
      !mobileMenuBtn?.contains(e.target)
    ) {
      toggleMobileMenu();
    }
  });
});

(function () {
  const trigger = document.getElementById("megaTrigger");
  const panel = document.getElementById("megaPanel");
  const overlay = document.getElementById("megaOverlay");
  const contactLink = document.getElementById("megaContactLink");

  if (!trigger || !panel) return;

  let closeTimer = null;

  function openMega() {
    clearTimeout(closeTimer);
    panel.classList.add("is-open");
    overlay.classList.add("is-open");
    trigger.classList.add("is-active");
    trigger.setAttribute("aria-expanded", "true");
  }

  function closeMega() {
    panel.classList.remove("is-open");
    overlay.classList.remove("is-open");
    trigger.classList.remove("is-active");
    trigger.setAttribute("aria-expanded", "false");
  }

  function scheduledClose() {
    closeTimer = setTimeout(closeMega, 120);
  }

  trigger.addEventListener("mouseenter", function () {
    // Close features panel if open
    var fp = document.getElementById("featPanel");
    var fo = document.getElementById("featOverlay");
    var ft = document.getElementById("featTrigger");
    if (fp) {
      fp.classList.remove("is-open");
      fo && fo.classList.remove("is-open");
      ft && ft.classList.remove("is-active");
      ft && ft.setAttribute("aria-expanded", "false");
    }
    openMega();
  });
  trigger.addEventListener("mouseleave", scheduledClose);
  panel.addEventListener("mouseenter", function () {
    clearTimeout(closeTimer);
  });
  panel.addEventListener("mouseleave", scheduledClose);
  overlay.addEventListener("click", closeMega);

  // Close on Escape
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape") closeMega();
  });

  // Close when clicking a link inside the panel that goes to #contact
  if (contactLink) {
    contactLink.addEventListener("click", closeMega);
  }

  // Close Kullanım Alanları when Features trigger is hovered (handled in featTrigger.mouseenter above)
  // but also do the reverse here so both panels don't stay open simultaneously:
  // (The featTrigger block handles closing this panel on its mouseenter)

  // ── Features Mega Menu ──────────────────────────────────────────────────────
  const featTrigger = document.getElementById("featTrigger");
  const featPanel = document.getElementById("featPanel");
  const featOverlay = document.getElementById("featOverlay");
  const featAllLink = document.getElementById("featAllLink");

  if (featTrigger && featPanel) {
    let featCloseTimer = null;

    function openFeat() {
      clearTimeout(featCloseTimer);
      // Close the other mega if open
      panel.classList.remove("is-open");
      overlay.classList.remove("is-open");
      trigger.classList.remove("is-active");
      trigger.setAttribute("aria-expanded", "false");
      // Open this one
      featPanel.classList.add("is-open");
      featOverlay.classList.add("is-open");
      featTrigger.classList.add("is-active");
      featTrigger.setAttribute("aria-expanded", "true");
    }

    function closeFeat() {
      featPanel.classList.remove("is-open");
      featOverlay.classList.remove("is-open");
      featTrigger.classList.remove("is-active");
      featTrigger.setAttribute("aria-expanded", "false");
    }

    function scheduledCloseFeat() {
      featCloseTimer = setTimeout(closeFeat, 120);
    }

    featTrigger.addEventListener("mouseenter", openFeat);
    featTrigger.addEventListener("mouseleave", scheduledCloseFeat);
    featPanel.addEventListener("mouseenter", function () {
      clearTimeout(featCloseTimer);
    });
    featPanel.addEventListener("mouseleave", scheduledCloseFeat);
    featOverlay.addEventListener("click", closeFeat);

    if (featAllLink) {
      featAllLink.addEventListener("click", closeFeat);
    }

    trigger.addEventListener("mouseenter", function () {
      clearTimeout(featCloseTimer);
      closeFeat();
    });

    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape") closeFeat();
    });
  }

  function initMobileAccordion(toggleId, linksId, chevronId) {
    const toggle = document.getElementById(toggleId);
    const links = document.getElementById(linksId);
    const chevron = document.getElementById(chevronId);
    if (!toggle || !links) return;
    toggle.addEventListener("click", function (e) {
      e.stopPropagation();
      const isOpen = !links.classList.contains("hidden");
      links.classList.toggle("hidden");
      if (chevron) chevron.style.transform = isOpen ? "" : "rotate(180deg)";
    });
  }

  initMobileAccordion("mobileUcToggle", "mobileUcLinks", "mobileUcChevron");

  initMobileAccordion(
    "mobileFeatToggle",
    "mobileFeatLinks",
    "mobileFeatChevron",
  );
})();

function updateHamburgerColor() {
  const mobileMenuBtn = document.getElementById("mobileMenuBtn");

  if (!mobileMenuBtn || isMobileMenuOpen) return;

  if (window.scrollY > 50) {
    mobileMenuBtn.classList.remove("text-slate-300", "hover:text-blue-300");
    mobileMenuBtn.classList.add("text-slate-800", "hover:text-blue-600");
  } else {
    mobileMenuBtn.classList.remove("text-slate-800", "hover:text-blue-600");
    mobileMenuBtn.classList.add("text-slate-300", "hover:text-blue-300");
  }
}

