function updateSeoForLanguage(language) {
  const m = seoMeta[language];
  if (!m) return;

  // <title>
  document.title = m.title;

  // <meta name="description">
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", m.description);

  // Open Graph
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute("content", m.title);
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc) ogDesc.setAttribute("content", m.description);
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogLocale) ogLocale.setAttribute("content", m.ogLocale);

  // Twitter / X
  const twTitle = document.querySelector('meta[name="twitter:title"]');
  if (twTitle) twTitle.setAttribute("content", m.title);
  const twDesc = document.querySelector('meta[name="twitter:description"]');
  if (twDesc) twDesc.setAttribute("content", m.description);

  // JSON-LD — update FAQPage, HowTo and SoftwareApplication in place
  const ldScript = document.querySelector('script[type="application/ld+json"]');
  if (!ldScript) return;
  try {
    const graph = JSON.parse(ldScript.textContent);
    (graph["@graph"] || []).forEach((node) => {
      if (node["@type"] === "SoftwareApplication") {
        node.description = m.softwareDesc;
      }
      if (node["@type"] === "FAQPage") {
        node.mainEntity = m.faq.map((item) => ({
          "@type": "Question",
          name: item.q,
          acceptedAnswer: { "@type": "Answer", text: item.a },
        }));
      }
      if (node["@type"] === "HowTo") {
        node.name = m.howTo.name;
        node.description = m.howTo.desc;
        node.step = m.howTo.steps.map((s, i) => ({
          "@type": "HowToStep",
          position: i + 1,
          name: s.name,
          text: s.text,
          url: "https://karne.app/#ai-content",
        }));
      }
    });
    ldScript.textContent = JSON.stringify(graph);
  } catch (e) {
    // silently skip — existing JSON-LD stays intact
  }
}

